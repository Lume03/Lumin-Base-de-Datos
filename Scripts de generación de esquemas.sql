-- Tablas de Contenido

CREATE TABLE LEVELS (
  ID_LEVEL   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME       VARCHAR2(100) NOT NULL
);

CREATE TABLE SECTION (
  ID_SECTION  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_LEVEL    NUMBER NOT NULL REFERENCES LEVELS(ID_LEVEL),
  NAME        VARCHAR2(120) NOT NULL,
  DESCRIPTION VARCHAR2(1000)
);

CREATE TABLE THEORY_MODULE (
  ID_THEORY_MODULE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SECTION       NUMBER NOT NULL REFERENCES SECTION(ID_SECTION)
);

CREATE TABLE PAGE (
  ID_PAGE          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_THEORY_MODULE NUMBER NOT NULL REFERENCES THEORY_MODULE(ID_THEORY_MODULE),
  NAME             VARCHAR2(200) NOT NULL,
  PAGE_ORDER       NUMBER NOT NULL,
  CONTENT_MD       CLOB
);

CREATE TABLE PRACTICE_MODULE (
  ID_PRACTICE_MODULE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SECTION         NUMBER NOT NULL REFERENCES SECTION(ID_SECTION)
);


-- TABLAS DE USUARIOS Y CUENTAS


CREATE TABLE APP_USER (
  ID_USER     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMAIL       VARCHAR2(200) NOT NULL,
  USERNAME    VARCHAR2(80)  NOT NULL,
  BIRTH_DATE  DATE,
  CREATED_AT  DATE DEFAULT SYSDATE NOT NULL,
  UPDATED_AT  DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE EXTERNAL_AUTH (
  ID_EXTERNAL   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USER       NUMBER NOT NULL REFERENCES APP_USER(ID_USER) ON DELETE CASCADE,
  PROVIDER      VARCHAR2(40) NOT NULL,
  PROVIDER_ID   VARCHAR2(200) NOT NULL,
  CREATED_AT    DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE USER_ACCOUNT (
  ID_ACCOUNT   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USER      NUMBER NOT NULL UNIQUE REFERENCES APP_USER(ID_USER) ON DELETE CASCADE,
  ID_PAGE      NUMBER REFERENCES PAGE(ID_PAGE)
);


ALTER TABLE USER_ACCOUNT ADD (
  LIVES        NUMBER DEFAULT 5 NOT NULL CHECK (LIVES >= 0 AND LIVES <= 5),
  NEXT_LIFE_AT DATE
);


-- TABLAS DE SUSCRIPCIONES

CREATE TABLE SUBSCRIPTION_PLAN (
  ID_PLAN        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME           VARCHAR2(60) NOT NULL,
  DURATION_DAYS  NUMBER NOT NULL CHECK (DURATION_DAYS > 0),
  PRICE          NUMBER
);

CREATE TABLE SUBSCRIPTION (
  ID_SUBSCRIPTION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USER         NUMBER NOT NULL REFERENCES APP_USER(ID_USER) ON DELETE CASCADE,
  ID_PLAN         NUMBER NOT NULL REFERENCES SUBSCRIPTION_PLAN(ID_PLAN),
  START_DATE      DATE NOT NULL,
  END_DATE        DATE NOT NULL,
  STATUS          VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL
    CHECK (STATUS IN ('ACTIVO','EXPIRADO','CANCELADO'))
);

-- TABLAS DE PROGRESO

CREATE TABLE USER_SECTION_PROGRESS (
  ID_USER      NUMBER NOT NULL REFERENCES APP_USER(ID_USER) ON DELETE CASCADE,
  ID_SECTION   NUMBER NOT NULL REFERENCES SECTION(ID_SECTION),
  STATUS       VARCHAR2(12) NOT NULL CHECK (STATUS IN ('BLOQUEADO','EN PROGRESO','APROBADO')),
  LAST_SCORE   NUMBER,
  ATTEMPTS     NUMBER DEFAULT 0 NOT NULL,
  COMPLETED_AT DATE,
  CONSTRAINT PK_USER_SECTION_PROGRESS PRIMARY KEY (ID_USER, ID_SECTION)
);

CREATE TABLE PRACTICE_ATTEMPT (
  ID_ATTEMPT   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USER      NUMBER NOT NULL REFERENCES APP_USER(ID_USER) ON DELETE CASCADE,
  ID_SECTION   NUMBER NOT NULL REFERENCES SECTION(ID_SECTION),
  SCORE        NUMBER, -- Se permite NULL al inicio
  ATTEMPTED_AT DATE DEFAULT SYSDATE NOT NULL,
  STATUS       VARCHAR2(20) DEFAULT 'IN_PROGRESS' NOT NULL,
  STARTED_AT   TIMESTAMP    DEFAULT SYSTIMESTAMP  NOT NULL,
  FINISHED_AT  TIMESTAMP    NULL,
  CHECK (SCORE BETWEEN 0 AND 5)
);


-- ÍNDICES 

-- Contenido
CREATE UNIQUE INDEX UQ_LEVELS_NAME ON LEVELS(NAME);
CREATE INDEX IX_SECTION_LEVEL ON SECTION(ID_LEVEL);
CREATE UNIQUE INDEX UQ_TM_SECTION ON THEORY_MODULE(ID_SECTION);
CREATE UNIQUE INDEX UQ_PAGE_TM_ORDER ON PAGE(ID_THEORY_MODULE, PAGE_ORDER);
CREATE INDEX IX_PAGE_TM ON PAGE(ID_THEORY_MODULE);
CREATE UNIQUE INDEX UQ_PM_SECTION ON PRACTICE_MODULE(ID_SECTION);

-- Usuarios
CREATE UNIQUE INDEX UQ_APP_USER_EMAIL ON APP_USER(EMAIL);
CREATE UNIQUE INDEX UQ_EXTAUTH_PROVIDER ON EXTERNAL_AUTH(PROVIDER, PROVIDER_ID);
CREATE INDEX IX_EXTAUTH_USER ON EXTERNAL_AUTH(ID_USER);
CREATE INDEX IX_UACC_PAGE ON USER_ACCOUNT(ID_PAGE);

-- Suscripciones
CREATE UNIQUE INDEX UQ_PLAN_NAME ON SUBSCRIPTION_PLAN(NAME);
CREATE INDEX IX_SUB_USER ON SUBSCRIPTION(ID_USER);

-- Progreso
CREATE INDEX IX_USP_SECTION ON USER_SECTION_PROGRESS(ID_SECTION);
CREATE INDEX IX_USP_USER ON USER_SECTION_PROGRESS(ID_USER);
CREATE INDEX IX_ATTEMPT_USER_SECTION ON PRACTICE_ATTEMPT(ID_USER, ID_SECTION);
CREATE INDEX IX_PA_USER_SECTION_STATUS ON PRACTICE_ATTEMPT (ID_USER, ID_SECTION, STATUS, STARTED_AT);